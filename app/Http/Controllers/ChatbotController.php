    public function sendMessage(Request $request)
    {
        try {
            Log::info('Chatbot message received', ['message' => $request->message]);

            $request->validate([
                'message' => 'required|string|max:1000'
            ]);

            $response = $this->getBotResponse($request->message);

            try {
                DB::table('chatbot_messages')->insert([
                    'session_id' => $request->session_id ?? session()->getId(),
                    'user_id' => Auth::id(),
                    'message' => $request->message,
                    'response' => $response,
                    'created_at' => now()
                ]);
            } catch (\Exception $dbError) {
                Log::error('DB save error: ' . $dbError->getMessage());
            }

            return response()->json([
                'success' => true,
                'response' => $response,
                'time' => now()->format('h:i A')
            ]);
        } catch (\Exception $e) {
            Log::error('Chatbot error: ' . $e->getMessage());

            return response()->json([
                'success' => true,
                'response' => $this->getFallbackResponse($request->message ?? ''),
                'time' => now()->format('h:i A')
            ]);
        }
    }

